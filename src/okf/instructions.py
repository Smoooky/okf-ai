class Repository:
    """Lookups with caching: nearest package.json, Makefile, justfile."""

    def __init__(self, root: Path, history: History | None = None):
        self.root = root
        self._history = history
        self._cache: dict[object, object] = {}

    @property
    def history(self) -> History:
        if self._history is None:
            self._history = History(toplevel(self.root))
        return self._history

    def ignored(self, path: Path) -> bool:
        """Ignored by git (.gitignore at any level) or a usual build output: may exist only after a build."""
        relative = _relative(path, self.root)
        if any(part in BUILD_OUTPUTS or part.startswith(".env") for part in Path(relative).parts):
            return True
        key = ("ignored", relative)
        if key not in self._cache:
            try:
                result = subprocess.run(["git", "check-ignore", "--no-index", "-q", "--", relative], cwd=self.root,
                                        capture_output=True, check=False)
                self._cache[key] = result.returncode == 0
            except OSError:
                self._cache[key] = False
        return self._cache[key]

    def moved(self, path: Path) -> tuple[Path, datetime | None] | None:
        """Where a file went if git history shows it was renamed."""
        return self.history.moved(path)

    def generates_makefiles(self) -> bool:
        return any((self.root / name).exists() for name in ("CMakeLists.txt", "configure.ac", "configure", "meson.build"))

    def by_suffix(self, path: str) -> list[Path]:
        """Files (or, for `dir/`, directories) whose path ends with `path`, for shortened mentions."""
        while path.startswith("./"):
            path = path[2:]
        wanted = path.rstrip("/")
        files, directories = self._index()
        name = wanted.rsplit("/", 1)[-1]
        pool = directories.get(name, []) if path.endswith("/") else files.get(name, []) + directories.get(name, [])
        return [self.root / p for p in pool if p.endswith("/" + wanted)]

    def _index(self) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
        """Repository files and directories by name: `git ls-files`, or a walk outside git."""
        if "index" not in self._cache:
            try:
                result = subprocess.run(["git", "ls-files", "-z"], cwd=self.root, capture_output=True, check=False)
                listed = result.stdout.decode("utf-8", "replace").split("\0") if result.returncode == 0 else []
            except OSError:
                listed = []
            if not listed or listed == [""]:
                listed = [
                    _relative(Path(d) / f, self.root)
                    for d, dirnames, filenames in os.walk(self.root)
                    for f in filenames
                    if not dirnames.__setitem__(slice(None), [n for n in dirnames if n not in SKIP_DIRS])
                ]
            files: dict[str, list[str]] = defaultdict(list)
            directories: dict[str, list[str]] = defaultdict(list)
            seen = set()
            for rel in filter(None, listed):
                files[rel.rsplit("/", 1)[-1]].append(rel)
                parent = rel.rsplit("/", 1)[0] if "/" in rel else ""
                while parent and parent not in seen:
                    seen.add(parent)
                    directories[parent.rsplit("/", 1)[-1]].append(parent)
                    parent = parent.rsplit("/", 1)[0] if "/" in parent else ""
            self._cache["index"] = (files, directories)
        return self._cache["index"]

    def nearest(self, start: Path, names: tuple[str, ...]) -> Path | None:
        directory = Path(os.path.normpath(start))
        while True:
            for name in names:
                if name in self._entries(directory) and (directory / name).is_file():
                    return directory / name
            if directory == self.root or directory.parent == directory or self.root not in directory.parents:
                return None
            directory = directory.parent

    def show(self, path: Path) -> str:
        """A path relative to the checked directory, for messages."""
        return _relative(path, self.root)

    def _entries(self, directory: Path) -> set[str]:
        """Exact file names (Windows and macOS file systems ignore case)."""
        key = ("entries", directory)
        if key not in self._cache:
            try:
                self._cache[key] = set(os.listdir(directory))
            except OSError:
                self._cache[key] = set()
        return self._cache[key]

    def package(self, path: Path) -> dict | None:
        if path not in self._cache:
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                data = None
            self._cache[path] = data if isinstance(data, dict) else None
        return self._cache[path]

    def make_targets(self, path: Path) -> tuple[set[str], bool]:
        """Targets of a Makefile, and whether it may define more (include, pattern rules)."""
        if path not in self._cache:
            targets, open_ended = set(), False
            for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
                if re.match(r"^\s*-?s?include\s", line):
                    open_ended = True
                match = re.match(r"^([^\s:=#][^:=#]*?)\s*::?(?!=)", line)
                if match:
                    for name in match.group(1).split():
                        if "%" in name or "$" in name:
                            open_ended = True
                        targets.add(name)
            self._cache[path] = (targets, open_ended)
        return self._cache[path]

    def just_recipes(self, path: Path) -> tuple[set[str], bool]:
        if path not in self._cache:
            recipes, open_ended = set(), False
            for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
                if re.match(r"^(import|mod)\b", line):
                    open_ended = True
                match = re.match(r"^alias\s+([\w-]+)\s*:=", line) or re.match(r"^@?([A-Za-z_][\w-]*)(?:\s+[^:]*)?:(?!=)", line)
                if match:
                    recipes.add(match.group(1))
            self._cache[path] = (recipes, open_ended)
        return self._cache[path]


def check_repository(root: Path, strict: bool = False, changes: list[Change] | None = None,
                     git_root: Path | None = None) -> Report:
    """Check every instruction file under `root`. `changes` paths are relative to `git_root`."""
    root = root.resolve()
    git_root = (git_root or root).resolve()
    repository = Repository(root)
    files = discover(root)
    issues: list[Issue] = []
    facts: dict[Path, _Facts] = {}
    paths = commands = 0
    for instruction in files:
        file_issues, file_facts, counts = _check_file(instruction, repository, strict, changes, git_root)
        issues.extend(file_issues)
        facts[instruction.path] = file_facts
        paths, commands = paths + counts[0], commands + counts[1]
    for instruction in files:
        agents = instruction.path.with_name("AGENTS.md")
        if instruction.name == "CLAUDE.md" and agents in facts:
            imported = _relative(agents, root) in facts[instruction.path].imports
            if not imported:  # CLAUDE.md that imports AGENTS.md says the same by construction
                issues.extend(_compare(facts[agents], facts[instruction.path], instruction.path))
    return Report(issues, len(files), paths, commands)


@dataclass(frozen=True)
class Reference:
    """One thing an instruction relies on, resolved against the repository."""

    line: int
    field: str  # "path", "command" or "globs"
    subject: str  # how messages name it: '"src/a.py"', '"pytest tests/a.py": tests/a.py'
    path: str | None = None  # a file or directory as written; None for scripts, targets and globs
    candidates: tuple[Path, ...] = ()  # where that file may be
    problem: str | None = None  # why a script, target or glob is missing
    sources: tuple[Path, ...] = ()  # existing files (or glob patterns) it relies on: the code it describes
    type: str = "path"  # path, glob, script (a file a command runs), npm-script, make, just
    status: str = "ok"  # ok, broken, unclear (looks like a placeholder), unknown (ignored by git), moved
    base: str = ""  # "root": found from the repository root rather than from the instruction's folder
    moved_to: Path | None = None
    moved_at: datetime | None = None
    origin: str = ""  # "import" for CLAUDE.md @imports
    moved_from: Path | None = None  # the candidate git saw renamed
    name: str = ""  # the script, target or recipe a command needs
    manifest: Path | None = None  # the package.json, Makefile or justfile looked at

    @property
    def missing(self) -> str | None:
        """Why the reference is broken, or None."""
        if self.problem:
            return self.problem
        if self.status == "broken":
            return f"{self.subject} does not exist"
        return None


@dataclass
class FileReferences:
    references: list[Reference]
    facts: _Facts
    paths: int = 0
    commands: int = 0
    error: str | None = None


def references(instruction: InstructionFile, repository: Repository, text: str | None = None) -> FileReferences:
    """Every path, command and glob an instruction file mentions, resolved."""
    facts = _Facts()
    if text is None:
        try:
            text = instruction.path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            return FileReferences([], facts, error=f"Cannot read file as UTF-8 text: {exc}")
    found: list[Reference] = []
    paths = commands = 0
    nested = Path(os.path.normpath(instruction.scope)) != Path(os.path.normpath(repository.root))
    for mention in mentions(text, claude=instruction.name == "CLAUDE.md"):
        if mention.kind == "path":
            candidates = _path_candidates(mention.text, instruction, repository.root)
            if mention.loose and not _first_segment_exists(mention.text, candidates):
                continue
            paths += 1
            subject = f'"{mention.text}"'
            if "*" in mention.text:
                matching = [c for c in candidates if glob.glob(str(c), recursive=True)]
                found.append(Reference(mention.line, "path", subject, sources=tuple(matching[:1]), type="glob",
                                       problem=None if matching else f"{subject} matches no files",
                                       status="ok" if matching else "broken"))
                continue
            facts.paths.append((_relative(_pick(candidates), repository.root), mention.text, mention.line))
            if mention.origin == "import":
                facts.imports.add(_relative(_pick(candidates), repository.root))
            found.append(_file_reference(mention.line, "path", subject, mention.text, candidates, repository,
                                         nested, "path", mention.origin, loose=mention.loose))
            continue
        commands += 1
        cwd = instruction.scope
        for words in split_commands(mention.text):
            command = " ".join(words)
            targets, cwd = analyze(words, cwd)
            for target in targets:
                if target.kind == "file":
                    candidates = [target.cwd / target.name, repository.root / target.name]
                    subject = f'"{command}"' if command == target.name else f'"{command}": {target.name}'
                    found.append(_file_reference(mention.line, "command", subject, target.name, candidates,
                                                 repository, nested, "script"))
                    continue
                message, manifest = _check_target(target, command, repository)
                kind = "npm-script" if target.kind == "script" else target.kind
                status = "broken" if message else "ok"
                if target.kind == "make" and manifest is None and repository.generates_makefiles():
                    message, status = None, "unknown"  # CMake, autotools or meson write the Makefile
                found.append(Reference(mention.line, "command", f'"{command}"', problem=message,
                                       sources=(manifest,) if manifest else (), type=kind, status=status,
                                       name=target.name, manifest=manifest))
                if target.kind == "script":
                    facts.managers.add(target.runner)
                    family = "script"
                else:
                    family = target.kind
                purpose = re.split(r"[:_\-.\s/]", target.name.lower())[0]
                facts.commands.append((purpose, f"{family}:{target.name}", command, mention.line))
    if instruction.path.suffix == ".mdc":
        for pattern, line in cursor_globs(text):
            matches = glob.glob(pattern, root_dir=instruction.scope, recursive=True)
            found.append(Reference(line, "globs", f'"{pattern}"', type="glob",
                                   sources=(instruction.scope / pattern,) if matches else (),
                                   problem=None if matches else f'"{pattern}" matches no files',
                                   status="ok" if matches else "broken"))
    return FileReferences(found, facts, paths, commands)


def _file_reference(line: int, field: str, subject: str, path: str, candidates: list[Path],
                    repository: Repository, nested: bool, kind: str, origin: str = "",
                    loose: bool = False) -> Reference:
    """A file or directory reference with its status: what exists, and why something does not.

    Only what is surely a path and surely missing is "broken": example paths and paths without an
    extension (`controller/service/db`) are "unclear", build outputs and paths outside the repository
    "unknown", a file git saw renamed "moved". A shortened path (`model/time.ts` for `src/model/time.ts`)
    that matches exactly one file is found by its end ("ok:suffix").
    """
    candidates = list(dict.fromkeys(Path(os.path.normpath(c)) for c in candidates))
    common = dict(path=path, candidates=tuple(candidates), type=kind, origin=origin)
    existing = [c for c in candidates if c.exists()]
    if existing:
        from_root = nested and len(candidates) > 1 and existing[0] == candidates[-1]
        return Reference(line, field, subject, sources=(existing[0],), base="root" if from_root else "", **common)
    if all(_relative(c, repository.root).startswith("../") for c in candidates):
        return Reference(line, field, subject, status="unknown", **common)  # outside the repository
    if is_placeholder(path):
        return Reference(line, field, subject, status="unclear", **common)
    if any(repository.ignored(c) for c in candidates):
        return Reference(line, field, subject, status="unknown", **common)
    for candidate in candidates:
        moved = repository.moved(candidate)
        if moved:
            return Reference(line, field, subject, status="moved", moved_to=moved[0], moved_at=moved[1],
                             moved_from=candidate, **common)
    matches = [] if path.startswith(("../", "/")) else repository.by_suffix(path)
    if len(matches) == 1:
        return Reference(line, field, subject, sources=(matches[0],), base="suffix", **common)
    doubtful = loose and not path.endswith("/") and not _EXT_RE.search(path.rsplit("/", 1)[-1])
    if matches or doubtful:
        return Reference(line, field, subject, status="unclear", **common)
    return Reference(line, field, subject, status="broken", **common)


def is_placeholder(path: str) -> bool:
    """`path/to/file.ts`, `src/foo`, `your-project/...`: an example, not a real file."""
    text = path.strip().lower()
    if "path/to/" in text or "..." in text or "…" in text:
        return True
    for part in text.strip("./").split("/"):
        stem = part.split(".", 1)[0]
        if stem in PLACEHOLDER_WORDS or part in PLACEHOLDER_WORDS:
            return True
    return False


def _check_file(instruction: InstructionFile, repository: Repository, strict: bool,
                changes: list[Change] | None, git_root: Path) -> tuple[list[Issue], _Facts, tuple[int, int]]:
    if instruction.alias_of or instruction.generated_from:
        return [Issue(INFO, instruction.path, "file", instruction.note(repository.root), 1)], _Facts(), (0, 0)
    found = references(instruction, repository)
    problem = ERROR if strict else WARNING
    if found.error:  # unreadable or not UTF-8: a problem like a broken path, an error only with --strict
        return [Issue(problem, instruction.path, "file", found.error)], found.facts, (0, 0)
    issues: list[Issue] = []

    def report(level: str, kind: str, message: str, line: int) -> None:
        issues.append(Issue(level, instruction.path, kind, f"{message} (line {line})", line))

    changed = {} if changes is None else _index_changes(changes)
    instruction_changed = _relative(instruction.path, git_root) in changed
    for reference in found.references:
        if reference.path is not None:
            _check_reference(reference, instruction, changed, instruction_changed, git_root, problem, report)
        elif reference.problem:
            report(problem, reference.field, reference.problem, reference.line)
    return issues, found.facts, (found.paths, found.commands)


def _check_reference(reference: Reference, instruction: InstructionFile, changed: dict[str, Change],
                     instruction_changed: bool, git_root: Path, problem: str, report) -> None:
    """A file or directory an instruction relies on: does it exist, did the change touch it?"""
    shown, line, kind = reference.subject, reference.line, reference.field
    relatives = {_relative(c, git_root) for c in reference.candidates}
    hits = [changed[r] for r in relatives if r in changed]
    if reference.status != "ok":
        renamed = next((c for c in hits if c.status in "RC" and c.old_path in relatives), None)
        if renamed is not None:
            new = Path(os.path.relpath(git_root / renamed.path, instruction.scope)).as_posix()
            report(problem, kind, f"{shown} was renamed to {new} in this change", line)
        elif hits and reference.status in ("broken", "moved"):
            report(problem, kind, f"{shown} was deleted or renamed in this change", line)
        elif reference.status == "moved":
            new = Path(os.path.relpath(reference.moved_to, instruction.scope)).as_posix()
            when = f" on {reference.moved_at.date().isoformat()}" if reference.moved_at else ""
            report(problem, kind, f"{shown} was moved to {new}{when}", line)
        elif reference.status == "unclear":
            report(INFO, kind, f"{shown} looks like a placeholder, not checked", line)
        elif reference.status == "unknown":
            report(INFO, kind, f"{shown} is ignored by git (a build output?), not checked", line)
        else:
            report(problem, kind, reference.missing, line)
        return
    touched = [c for c in hits if c.status != "D" and c.path in relatives]
    if touched and Path(reference.path).suffix.lower() not in DOCUMENT_SUFFIXES:  # editing a linked doc is routine
        if instruction_changed:
            report(INFO, kind, f"{shown} changed; the instruction was updated in the same change", line)
        else:
            report(WARNING, kind, f"{shown} changed in this change; the instruction may be outdated", line)


def _check_target(target: Target, command: str, repository: Repository) -> tuple[str | None, Path | None]:
    """Why the script, make target or just recipe a command needs is missing, and the file defining it."""
    if target.kind == "script":
        package = repository.nearest(target.cwd, ("package.json",))
        if package is None:
            return f'"{command}": no package.json found', None
        data = repository.package(package)
        if data is None:
            return f'"{command}": {repository.show(package)} is not valid JSON', package
        manager = _package_manager(package.parent, data)
        if manager and manager[0] != target.runner:
            return f'"{command}": this project uses {manager[0]} ({manager[1]})', package
        scripts = data.get("scripts") if isinstance(data.get("scripts"), dict) else {}
        dependencies = {**(data.get("dependencies") or {}), **(data.get("devDependencies") or {})}
        if target.name in scripts or (target.shorthand and target.name in dependencies):
            return None, package
        if target.name == "start" and (package.parent / "server.js").exists():
            return None, package
        return f'"{command}": no script "{target.name}" in {repository.show(package)}', package
    if target.kind == "make":
        makefile = target.makefile or repository.nearest(target.cwd, ("GNUmakefile", "makefile", "Makefile"))
        if makefile is None or not makefile.is_file():
            return f'"{command}": no Makefile found', None
        targets, open_ended = repository.make_targets(makefile)
        if target.name in targets or open_ended:
            return None, makefile
        return f'"{command}": no target "{target.name}" in {repository.show(makefile)}', makefile
    justfile = repository.nearest(target.cwd, ("justfile", "Justfile", ".justfile"))
    if justfile is None:
        return f'"{command}": no justfile found', None
    recipes, open_ended = repository.just_recipes(justfile)
    if target.name in recipes or open_ended:
        return None, justfile
    return f'"{command}": no recipe "{target.name}" in {repository.show(justfile)}', justfile


def _package_manager(directory: Path, data: dict) -> tuple[str, str] | None:
    declared = data.get("packageManager")
    if isinstance(declared, str) and declared:
        return declared.split("@", 1)[0], '"packageManager" in package.json'
    for lockfile, manager in LOCKFILES:
        if (directory / lockfile).exists():
            return manager, lockfile
    return None


def _compare(agents: _Facts, claude: _Facts, claude_path: Path) -> list[Issue]:
    """AGENTS.md and CLAUDE.md in one directory should not send agents different ways."""
    issues = []

    def disagree(message: str, line: int) -> None:
        issues.append(Issue(WARNING, claude_path, "consistency",
                            f"Instructions for different agents disagree: {message} (line {line})", line))

    by_purpose_a, by_purpose_c = defaultdict(list), defaultdict(list)
    for purpose, key, command, line in agents.commands:
        by_purpose_a[purpose].append((key, command, line))
    for purpose, key, command, line in claude.commands:
        by_purpose_c[purpose].append((key, command, line))
    for purpose in sorted(set(by_purpose_a) & set(by_purpose_c)):
        a, c = by_purpose_a[purpose], by_purpose_c[purpose]
        if {key for key, _, _ in a}.isdisjoint(key for key, _, _ in c):
            disagree(f'AGENTS.md runs "{a[0][1]}", CLAUDE.md runs "{c[0][1]}"', c[0][2])

    if agents.managers and claude.managers and agents.managers.isdisjoint(claude.managers):
        line = next(line for _, key, _, line in claude.commands if key.startswith("script:"))
        disagree(f"AGENTS.md uses {', '.join(sorted(agents.managers))}, "
                 f"CLAUDE.md uses {', '.join(sorted(claude.managers))}", line)

    by_name_a, by_name_c = defaultdict(set), defaultdict(list)
    for path, written, _ in agents.paths:
        by_name_a[Path(path).name].add(path)
    for path, written, line in claude.paths:
        by_name_c[Path(path).name].append((path, written, line))
    for name in sorted(set(by_name_a) & set(by_name_c)):
        mine = by_name_c[name]
        if by_name_a[name].isdisjoint(path for path, _, _ in mine):
            other = sorted(by_name_a[name])[0]
            disagree(f'AGENTS.md mentions "{other}", CLAUDE.md mentions "{mine[0][1]}"', mine[0][2])
    return issues


def _index_changes(changes: list[Change]) -> dict[str, Change]:
    index = {}
    for change in changes:
        index[change.path] = change
        if change.old_path:
            index[change.old_path] = change
    return index


def _path_candidates(path: str, instruction: InstructionFile, root: Path) -> list[Path]:
    if path.startswith("/"):
        bases = [root]
    else:
        bases = [instruction.path.parent, instruction.scope, root]
    result = []
    for base in bases:
        candidate = Path(os.path.normpath(base / path.lstrip("/")))
        if candidate not in result:
            result.append(candidate)
    return result


def _first_segment_exists(path: str, candidates: list[Path]) -> bool:
    depth = len([part for part in path.rstrip("/").split("/") if part not in (".", "")]) - 1
    for candidate in candidates:
        first = candidate
        for _ in range(depth):
            first = first.parent
        if first.exists():
            return True
    return False


def _pick(candidates: list[Path]) -> Path:
    return next((c for c in candidates if c.exists()), candidates[0])


def _relative(path: Path, root: Path) -> str:
    try:
        return Path(os.path.relpath(path, root)).as_posix()
    except ValueError:  # another drive on Windows
        return path.as_posix()
