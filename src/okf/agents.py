"""`okf agents`: AGENTS.md, a compact router so agents load bundle documents lazily."""

from __future__ import annotations

import os
from datetime import datetime, timedelta, timezone
from pathlib import Path

from okf import __version__, schema
from okf.bundle import Bundle, Document
from okf.report import WARNING, Issue

EXPIRING = timedelta(days=30)

# The front matter keeps AGENTS.md a conformant OKF concept for other OKF consumers.
HEADER = f"""\
---
type: Agent Router
title: Agent router
description: Compact table of contents of this bundle for AI agents, generated by okf agents.
generated: {{ by: okf-ai/{__version__} }}
---

# AGENTS.md

<!-- Generated by `okf agents` from the documents' front matter. Do not edit by hand. -->

This is the router of an OKF knowledge bundle. Do not read the whole bundle:
pick the documents relevant to your task from the table and open only those.

- **Freshness** comes from `stale_after`: `fresh until` is inside the review window, `review due` expires
  within {EXPIRING.days} days, `stale since` is past it, so check the document against its `sources` first.
  `draft` and `deprecated` documents say so before the freshness.
- **Trust** is the tier from `verified`: `human-reviewed` > `machine-confirmed` > `unverified`,
  plus who wrote the content (`generated.by`). When documents disagree, prefer the human-reviewed one.
"""


def render_agents(bundle: Bundle, now: datetime, output: Path) -> tuple[str, list[Issue]]:
    """AGENTS.md text for the bundle, plus warnings about documents left out of it."""
    out_dir = output.parent
    skipped, rows = [], []
    for doc in bundle.concepts():
        if doc.meta is None:
            skipped.append(
                Issue(WARNING, doc.path, "frontmatter", "Left out of AGENTS.md: front matter is missing or invalid")
            )
        else:
            rows.append(doc)
    rows.sort(key=lambda doc: (_text(doc.get("type", "")).lower(), doc.rel))

    lines = [HEADER]
    service = [doc for doc in bundle.documents if doc.rel in schema.RESERVED_FILES]
    if service:
        notes = {"index.md": "table of contents for humans", "log.md": "change log"}
        links = ", ".join(f"[{doc.rel}]({_link(doc, out_dir)}) ({notes[doc.rel]})" for doc in service)
        lines.append(f"Service files: {links}.\n")

    lines.append(f"## Documents ({len(rows)})\n")
    lines.append("| Document | Type | Tags | Freshness | Trust | Path |")
    lines.append("|---|---|---|---|---|---|")
    for doc in rows:
        cells = [_document(doc), _text(doc.get("type", "")), _tags(doc), freshness_status(doc, now), trust(doc)]
        cells.append(f"[{doc.rel}]({_link(doc, out_dir)})")
        lines.append("| " + " | ".join(_cell(cell) for cell in cells) + " |")
    return "\n".join(lines) + "\n", skipped


def freshness_status(doc: Document, now: datetime) -> str:
    expires = schema.stale_after(doc)
    if expires is None:
        result = "no stale_after"
    else:
        day = expires.astimezone(timezone.utc).date()
        if now >= expires:
            result = f"stale since {day}"
        elif expires - now <= EXPIRING:
            result = f"review due {day}"
        else:
            result = f"fresh until {day}"
    lifecycle = schema.status(doc)
    return result if lifecycle == schema.DEFAULT_STATUS else f"{lifecycle}, {result}"


def trust(doc: Document) -> str:
    author = schema.generated_by(doc)
    if author is None:
        return schema.trust_tier(doc)
    return f"{schema.trust_tier(doc)}, written by {author}"


def _document(doc: Document) -> str:
    description = doc.get("description", None)
    if isinstance(description, str) and description.strip():
        return f"{doc.title}: {description.strip()}"
    return doc.title


def _tags(doc: Document) -> str:
    tags = doc.get("tags", None)
    return ", ".join(str(tag) for tag in tags) if isinstance(tags, list) else ""


def _text(value: object) -> str:
    return value if isinstance(value, str) else ""


def _link(doc: Document, out_dir: Path) -> str:
    return Path(os.path.relpath(doc.path, out_dir)).as_posix().replace(" ", "%20")


def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")
