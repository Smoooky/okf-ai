"""`okf trust` and `okf verify`: which instructions and knowledge for AI agents can be trusted right now.

A unit is a section of an agent instruction file (split by `##` headings) or one OKF
knowledge file. For each unit okf finds the code it describes (paths and commands in the
text, `sources` in OKF front matter), the last confirmation (`.okf/trust.yml` for
instructions, `verified` for OKF) and the git history of both, and gives it a level:

- broken: it points to something that does not exist;
- recheck: the code changed after the last confirmation (or, never confirmed, after the
  section was last edited), or the section itself changed after it was confirmed;
- human-verified / process-verified: confirmed after the last change of its code;
- unverified: never confirmed, nothing changed since it was written.
"""

from __future__ import annotations

import hashlib
import os
import re
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

import yaml

from okf import schema
from okf.bundle import Bundle, Document, load_document, load_yaml
from okf.git import Change, History, changed_lines, changed_paths
from okf.instructions import (
    DOCUMENT_SUFFIXES, FENCE_INFO_RE, SKIP_DIRS, InstructionFile, Repository, discover, front_matter_end,
    instruction_scope, references,
)
from okf.sources import Check, Registry, registry
from okf.values import parse_instant

LEVELS = ("broken", "recheck", "human-verified", "process-verified", "unverified")
SIDECAR = Path(".okf") / "trust.yml"
ROUTER_MARK = "Generated by `okf agents`"
# Build tool wrappers change with the tool version, not with what a section describes.
WRAPPERS = {"gradlew", "gradlew.bat", "mvnw", "mvnw.cmd"}
_HEADING_RE = re.compile(r"^(#{1,6})\s+(.+?)\s*#*\s*$")
_PLAIN_ACTOR_RE = re.compile(r"^[\w:@.+\-/]+$")


class TrustError(RuntimeError):
    pass


@dataclass
class Unit:
    name: str  # "AGENTS.md#Auth" or "knowledge/auth_flow.md", relative to the checked directory
    path: Path
    section: str | None
    line: int
    kind: str  # "instruction" or "knowledge"
    sources: list[Path] = field(default_factory=list)  # code it describes: existing files, directories, globs
    touched: list[Path] = field(default_factory=list)  # every path it relies on, existing or not
    broken: list[str] = field(default_factory=list)
    verifications: list[tuple[datetime, str]] = field(default_factory=list)  # (at, by)
    text_hash: str | None = None
    recorded_hash: str | None = None
    generated_at: datetime | None = None
    stale_after: datetime | None = None
    last_edited: datetime | None = None
    generated_by: str | None = None  # who wrote the current text: okf fix, an LLM draft, OKF `generated.by`
    level: str = "unverified"
    message: str = ""
    changed: list[tuple[str, datetime]] = field(default_factory=list)  # sources newer than the reference date
    in_change: list[str] = field(default_factory=list)  # sources a pull request changed
    updated_in_change: bool = False  # the pull request also edited this section or document
    moved: list[tuple[str, str, datetime | None]] = field(default_factory=list)  # (as written, new path, when)
    broken_types: list[str] = field(default_factory=list)
    links: list[dict] = field(default_factory=list)  # every reference, for okf scan and --json
    remote: list[Check] = field(default_factory=list)  # Confluence pages, Jira issues, other URLs in `sources`
    end: int = 0
    reason: str = ""  # a short code for statistics, e.g. "broken:npm-script", "recheck:moved"


@dataclass
class TrustMap:
    units: list[Unit]
    root: Path
    since: bool = False
    notes: list[tuple[Path, str]] = field(default_factory=list)  # generated copies and links: checked elsewhere
    shallow: bool = False

    def count(self, *levels: str) -> int:
        return sum(unit.level in levels for unit in self.units)

    def summary(self) -> str:
        text = (
            f"okf trust: {len(self.units)} units: {self.count('human-verified', 'process-verified')} verified and "
            f"current, {self.count('recheck')} to recheck, {self.count('broken')} broken, "
            f"{self.count('unverified')} not verified"
        )
        if self.since:
            text += f"; {len(self.in_change())} to recheck because of this change"
        return text

    def in_change(self) -> list[Unit]:
        """Units whose code a pull request changed without touching the unit itself."""
        return [u for u in self.units if u.in_change and not u.updated_in_change]


# --- Building the map ----------------------------------------------------------------


def build_map(root: Path, history: History, changes: list[Change] | None = None,
              bundles: list[Path] | None = None, now: datetime | None = None,
              base_commit: str | None = None, sources: Registry | None = None) -> TrustMap:
    """The trust map of `root`. With `changes` (and the `base_commit` they start from), also what a
    pull request changed; a section or document the same change edited is not asked to be rechecked.
    `sources`: connectors for remote resources, configured from the environment by default."""
    root = Path(root).resolve()
    now = now or datetime.now(timezone.utc)
    instructions, notes = instruction_units(root, history)
    units = instructions + knowledge_units(root, history, bundles, sources)
    changed = None if changes is None else set(changed_paths(changes))
    if changed is not None:
        _mark_updated(units, history, changed, base_commit)
    for unit in units:
        _evaluate(unit, root, history, changed, now)
    order = {level: i for i, level in enumerate(LEVELS)}
    units.sort(key=lambda u: order[u.level])  # stable: file order within a level
    return TrustMap(units, root, since=changes is not None, notes=notes, shallow=history.shallow)


def _mark_updated(units: list[Unit], history: History, changed: set[str], base_commit: str | None) -> None:
    lines_by_file: dict[Path, set[int]] = {}
    for unit in units:
        relative = history.relative(unit.path) if history.root else None
        if relative is None or relative not in changed:
            continue
        if unit.kind == "knowledge" or base_commit is None:
            unit.updated_in_change = True
            continue
        if unit.path not in lines_by_file:
            lines_by_file[unit.path] = changed_lines(history.root, base_commit, relative)
        unit.updated_in_change = any(unit.line <= n <= unit.end for n in lines_by_file[unit.path])


def instruction_units(root: Path, history: History) -> tuple[list[Unit], list[tuple[Path, str]]]:
    repository = Repository(root, history)
    sidecars = _Sidecars(history.root)
    units, notes = [], []
    for instruction in discover(root):
        if instruction.alias_of or instruction.generated_from:
            notes.append((instruction.path, instruction.note(root)))
            continue
        try:
            text = instruction.path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if ROUTER_MARK in text:
            continue  # the OKF router is regenerated from the bundle
        found = references(instruction, repository, text)
        lines = text.split("\n")
        dates = history.line_dates(instruction.path)
        sidecar = sidecars.find(instruction.path.parent)
        for title, start, end in sections(text):
            inside = [r for r in found.references if start <= r.line <= end]
            unit = Unit(_unit_name(instruction.path, root, title), instruction.path, title, start, "instruction")
            unit.end = end
            unit.sources = instruction_sources(inside)
            unit.touched = _unique([*unit.sources, *(c for r in inside for c in r.candidates if not c.is_dir())])
            unit.broken = [r.missing for r in inside if r.missing]
            unit.broken_types = [r.type for r in inside if r.missing]
            unit.moved = [(r.path, _relative(r.moved_to, instruction.scope), r.moved_at)
                          for r in inside if r.status == "moved"]
            unit.links = [_link(r, lines, root) for r in inside]
            unit.text_hash = section_hash(lines[start - 1 : end])
            edited = [d for d in dates[start - 1 : end] if d is not None]
            unit.last_edited = max(edited) if edited else None
            if sidecar is not None:
                record = sidecar.record(_unit_name(instruction.path, sidecar.base, title))
                if record:
                    unit.verifications = _verifications(record.get("verified"))
                    unit.recorded_hash = record.get("hash")
                    generated = record.get("generated") if isinstance(record.get("generated"), dict) else {}
                    unit.generated_at = parse_instant(generated.get("at"))
                    unit.generated_by = generated.get("by")
            units.append(unit)
    return units, notes


def instruction_sources(found: list) -> list[Path]:
    """The files a part of an instruction describes.

    Globs (`src/**/*.py`, Cursor `globs:`) and directories (`src/`) say where something lives or
    applies, and linked or imported documents (`docs/x.md`, `@AGENTS.md`) are texts of their own:
    neither is code the part describes, and every change in them would ask for a recheck. So are
    the manifests behind `npm run` and `make` (a dependency bump changes package.json, not the
    command; a missing script is reported as broken anyway) and build tool wrappers (`./gradlew`).
    """
    return _unique(
        s for r in found if r.type in ("path", "script") for s in r.sources
        if "*" not in str(s) and not Path(s).is_dir() and Path(s).suffix.lower() not in DOCUMENT_SUFFIXES
        and Path(s).name not in WRAPPERS
    )


def _link(reference, lines: list[str], root: Path) -> dict:
    if reference.path is not None:
        source = _relative(reference.sources[0], root) if reference.sources else reference.path
    else:
        source = reference.subject.strip('"')
        if reference.sources and reference.type != "glob":
            source += f" ({_relative(reference.sources[0], root)})"
    text = lines[reference.line - 1].strip() if 0 < reference.line <= len(lines) else ""
    status = reference.status + (f":{reference.base}" if reference.base else "")
    return {"line": reference.line, "type": reference.type, "status": status, "source": source, "text": text[:240]}


def knowledge_units(root: Path, history: History, bundles: list[Path] | None = None,
                    sources: Registry | None = None) -> list[Unit]:
    sources = sources if sources is not None else registry(root=root, history=history)
    units = []
    for path, bundle_root in _concepts(root, bundles):
        doc = load_document(path, bundle_root)
        if doc.meta is None:
            continue
        unit = Unit(_relative(path, root), path, None, 1, "knowledge")
        for resource in schema.sources(doc):
            if any(ch.isspace() for ch in resource):
                continue  # a scope descriptor, not a path
            connector = sources.find(resource)
            if connector is not sources.git:
                unit.remote.append(sources.check(resource))  # status "unknown" without a configured connector
                continue
            candidates = [root / p for p in sources.git.paths(resource, doc, bundle_root, root)]
            if not candidates:
                continue
            unit.touched.extend(candidates)
            existing = [c for c in candidates if c.exists()]
            moved = None if existing else next(filter(None, (history.moved(c) for c in candidates)), None)
            if existing:
                unit.sources.append(existing[0])
            elif moved:
                unit.moved.append((resource, _relative(moved[0], root), moved[1]))
            else:
                unit.broken.append(f'source "{resource}" does not exist')
                unit.broken_types.append("source")
        unit.sources, unit.touched = _unique(unit.sources), _unique(unit.touched)
        unit.verifications = _verifications(doc.get("verified", None))
        unit.generated_at = parse_instant(doc.get("generated.at", None))
        unit.generated_by = schema.generated_by(doc)
        unit.stale_after = schema.stale_after(doc)
        unit.last_edited = history.last_change(path)
        units.append(unit)
    return units


def sections(text: str) -> list[tuple[str | None, int, int]]:
    """(title, first line, last line) of each `##` section; the text before the first one is a unit too.

    A file without `##` headings is one unit. Titles repeat as "Title (2)".
    """
    lines = text.split("\n")
    while lines and not lines[-1].strip():
        lines.pop()
    first = front_matter_end(lines)
    headings, fence = [], None
    for number in range(first + 1, len(lines) + 1):
        line = lines[number - 1]
        match = FENCE_INFO_RE.match(line)
        if fence is not None:
            if match and match.group(1)[0] == fence[0] and len(match.group(1)) >= len(fence) and not match.group(2):
                fence = None
            continue
        if match:
            fence = match.group(1)
            continue
        heading = _HEADING_RE.match(line)
        if heading and len(heading.group(1)) == 2:
            headings.append((heading.group(2), number))
    if not lines:
        return []
    if not headings:
        return [(None, 1, len(lines))]
    result = []
    intro = lines[first : headings[0][1] - 1]
    if any(line.strip() and not _HEADING_RE.match(line) for line in intro):
        result.append((None, 1, headings[0][1] - 1))
    seen: dict[str, int] = {}
    for i, (title, start) in enumerate(headings):
        end = headings[i + 1][1] - 1 if i + 1 < len(headings) else len(lines)
        seen[title] = seen.get(title, 0) + 1
        result.append((title if seen[title] == 1 else f"{title} ({seen[title]})", start, end))
    return result


def section_hash(lines: list[str]) -> str:
    text = "\n".join(line.rstrip() for line in lines).strip()
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


@dataclass
class _Dated:
    """A source and the moment it last changed: a file, a Confluence page, a closed Jira epic."""

    label: str
    at: datetime
    verb: str = "changed"
    reason: str = "recheck:code-changed"
    path: Path | None = None  # a file of this repository

    def says(self) -> str:
        return f"{self.label} {self.verb} {_day(self.at)}"


def _evaluate(unit: Unit, root: Path, history: History, changed: set[str] | None, now: datetime) -> None:
    dated = [_Dated(_show(s, root), d, path=s) for s in unit.sources if (d := history.last_change(s)) is not None]
    dated += [_Dated(r.signal.subject, r.signal.at, r.signal.verb, r.signal.reason) for r in unit.remote if r.signal]
    newest = max(dated, key=lambda item: item.at) if dated else None
    latest = max(unit.verifications, default=None)
    last = f"last verified {_day(latest[0])} by {latest[1]}" if latest else "never verified"

    if changed is not None:
        for path in unit.touched:
            relative = history.relative(path) if history.root else None
            if relative and any(c == relative or c.startswith(relative.rstrip("/") + "/") for c in changed):
                unit.in_change.append(_show(path, root))
        unit.in_change = sorted(set(unit.in_change))

    def result(level: str, message: str, reason: str) -> None:
        unit.level, unit.message, unit.reason = level, message, reason

    if unit.broken:
        more = f" (and {len(unit.broken) - 1} more)" if len(unit.broken) > 1 else ""
        return result("broken", unit.broken[0] + more, f"broken:{unit.broken_types[0]}")
    if unit.moved:
        old, new, when = unit.moved[0]
        on = f" on {_day(when)}" if when else ""
        return result("recheck", f"{old} moved to {new}{on}; {last}", "recheck:moved")
    if unit.in_change and not unit.updated_in_change:
        return result("recheck", f"{', '.join(unit.in_change)} changed in this change; {last}", "recheck:in-change")
    machine = unit.generated_by and not schema.is_human(unit.generated_by)
    if machine and unit.generated_at and (latest is None or unit.generated_at > latest[0]):
        # okf fix, an LLM draft or okf import wrote it: lower trust until a person confirms (okf verify)
        since = f", {last}" if latest else ""
        later = [d for d in dated if d.at > unit.generated_at]
        if later:  # and its source moved on after that
            unit.changed = [(d.label, d.at) for d in later if d.path]
            source = max(later, key=lambda d: d.at)
            return result("recheck", f"{source.says()}, after {unit.generated_by} wrote it on "
                          f"{_day(unit.generated_at)}; not verified{since}", source.reason)
        return result("unverified", f"edited by {unit.generated_by} on {_day(unit.generated_at)}; not verified{since}",
                      "unverified:generated")
    if latest is not None:
        newer = [d for d in dated if d.at > latest[0]]
        unit.changed = [(d.label, d.at) for d in newer if d.path]
        if unit.recorded_hash and unit.text_hash and unit.recorded_hash != unit.text_hash:
            return result("recheck", f"section edited after it was verified; {last}", "recheck:edited")
        if unit.generated_at and unit.generated_at > latest[0]:
            return result("recheck", f"content regenerated {_day(unit.generated_at)} after it was verified; {last}",
                          "recheck:regenerated")
        if unit.stale_after and now >= unit.stale_after:
            return result("recheck", f"stale_after {_day(unit.stale_after)} has passed; {last}", "recheck:stale-after")
        if newer:
            source = max(newer, key=lambda d: d.at)
            return result("recheck", f"{source.says()}, {last}", source.reason)
        humans = [v for v in unit.verifications if schema.is_human(v[1])]
        human = max(humans, default=None)
        verified = human if human and (newest is None or human[0] >= newest.at) else None
        level = "human-verified" if verified else "process-verified"
        verified = verified or latest
        return result(level, f"verified {_day(verified[0])} by {verified[1]}" + _sources_note(unit), "verified")
    if unit.stale_after and now >= unit.stale_after:
        return result("recheck", f"stale_after {_day(unit.stale_after)} has passed; never verified",
                      "recheck:stale-after")
    if newest and unit.last_edited and newest.at > unit.last_edited:
        unit.changed = [(d.label, d.at) for d in dated if d.path and d.at > unit.last_edited]
        what = "section" if unit.kind == "instruction" else "file"
        return result("recheck", f"{newest.says()}, {what} last edited {_day(unit.last_edited)} and never verified",
                      newest.reason)
    edited = f"; last edited {_day(unit.last_edited)}" if unit.last_edited else ""
    reason = "unverified" if unit.sources or _readable(unit) else "unverified:no-sources"
    return result("unverified", f"not verified{edited}" + _sources_note(unit), reason)


def _readable(unit: Unit) -> list[Check]:
    return [r for r in unit.remote if r.status == "ok"]


def _sources_note(unit: Unit) -> str:
    note = "; sources unchanged since" if unit.sources or _readable(unit) else "; no code references found"
    unknown = [r for r in unit.remote if r.actionable]
    if unknown:
        more = f" (and {len(unknown) - 1} more)" if len(unknown) > 1 else ""
        note += f"; {unknown[0].resource}: unknown, {unknown[0].message}{more}"
    return note


def unit_json(unit: Unit, root: Path) -> dict:
    def stamp(moment):
        return moment.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ") if moment else None

    return {
        "unit": unit.name,
        "file": _relative(unit.path, root),
        "section": unit.section,
        "line": unit.line,
        "kind": unit.kind,
        "level": unit.level,
        "reason": unit.reason,
        "message": unit.message,
        "sources": [_relative(s, root) for s in unit.sources],
        "changed": [{"path": path, "at": stamp(at)} for path, at in unit.changed],
        "in_change": unit.in_change,
        "updated_in_change": unit.updated_in_change,
        "broken": unit.broken,
        "moved": [{"from": old, "to": new, "at": stamp(at)} for old, new, at in unit.moved],
        "verified": [{"by": by, "at": stamp(at)} for at, by in sorted(unit.verifications)],
        "last_edited": stamp(unit.last_edited),
        "links": unit.links,
        "remote": [{"resource": r.resource, "connector": r.connector, "status": r.status, "message": r.message,
                    "last_modified": stamp(r.last_modified),
                    "signal": {"what": f"{r.signal.subject} {r.signal.verb}", "at": stamp(r.signal.at)}
                    if r.signal else None} for r in unit.remote],
    }


# --- Confirming: okf verify -----------------------------------------------------------


class Sidecar:
    """`.okf/trust.yml`: confirmations of agent instruction sections, keyed relative to its directory."""

    def __init__(self, path: Path):
        self.path = path
        self.base = path.parent.parent
        self.units: dict[str, dict] = {}
        if path.exists():
            data = load_yaml(path.read_text(encoding="utf-8"))
            records = data.get("units") if isinstance(data, dict) else None
            for record in records if isinstance(records, list) else []:
                if isinstance(record, dict) and isinstance(record.get("unit"), str):
                    self.units[record["unit"]] = record

    def record(self, unit: str) -> dict | None:
        return self.units.get(unit)

    def generated(self, unit: str, by: str, at: str, text_hash: str) -> None:
        """Record that a tool rewrote the section: not a confirmation, it lowers trust until `okf verify`."""
        record = self.units.setdefault(unit, {"unit": unit})
        record["generated"] = {"by": by, "at": at}
        record["generated_hash"] = text_hash

    def add(self, unit: str, by: str, at: str, sources: list[str], text_hash: str) -> None:
        record = self.units.setdefault(unit, {"unit": unit})
        record["hash"] = text_hash
        record["sources"] = sources
        record["verified"] = [*(record.get("verified") or []), {"by": by, "at": at}]

    def save(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        records = [self.units[name] for name in sorted(self.units)]
        body = yaml.safe_dump({"units": records}, allow_unicode=True, sort_keys=False, width=1000)
        header = "# okf-ai trust records: who confirmed which agent instruction sections, and when.\n" \
                 "# Written by `okf verify`; the hash detects edits made after a confirmation.\n"
        self.path.write_text(header + body, encoding="utf-8", newline="\n")


class _Sidecars:
    def __init__(self, stop: Path | None):
        self.stop = stop
        self._cache: dict[Path, Sidecar | None] = {}

    def find(self, start: Path) -> Sidecar | None:
        start = Path(start).resolve()
        if start not in self._cache:
            path = find_sidecar(start, self.stop)
            self._cache[start] = Sidecar(path) if path else None
        return self._cache[start]


def find_sidecar(start: Path, stop: Path | None) -> Path | None:
    """The nearest `.okf/trust.yml` from `start` up to `stop` (the git root) or the file system root."""
    directory = Path(start).resolve()
    while True:
        if (directory / SIDECAR).is_file():
            return directory / SIDECAR
        if (stop and directory == Path(stop).resolve()) or directory.parent == directory:
            return None
        directory = directory.parent


def default_actor(cwd: Path) -> str:
    """human:<git user.email>, else human:<user.name>."""
    for key in ("user.email", "user.name"):
        try:
            value = subprocess.run(["git", "config", key], cwd=cwd, capture_output=True, text=True,
                                   encoding="utf-8").stdout.strip()
        except OSError:
            value = ""
        if value:
            return "human:" + re.sub(r"\s+", "-", value)
    raise TrustError("cannot tell who verifies: set git config user.email or pass --by human:<id>")


def verify(target: str, by: str, at: datetime, cwd: Path, git_root: Path | None) -> list[str]:
    """Record a confirmation of `file[#section]`. Returns the confirmed unit names."""
    if not schema.is_actor(by):
        raise TrustError(f'"{by}" is not an actor: use human:<id>, process:<id> or <producer>/<version>')
    file_part, hash_mark, section = target.partition("#")
    path = (cwd / file_part).resolve()
    if not path.is_file():
        raise TrustError(f"file not found: {file_part}")
    stamp = at.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    scope = instruction_scope(path, Path(path.anchor))
    if scope is not None:
        wanted = section if hash_mark else None  # "AGENTS.md#": only the text before the first section
        return _verify_instruction(InstructionFile(path, scope), wanted, by, stamp, cwd, git_root)
    if section:
        raise TrustError(f"{file_part} is an OKF document: it has no sections to verify")
    _verify_knowledge(path, by, stamp)
    return [file_part]


def verify_units(units: list[Unit], by: str, at: datetime, cwd: Path, git_root: Path | None) -> list[str]:
    done = []
    for unit in units:
        target = f"{unit.path}#{unit.section or ''}" if unit.kind == "instruction" else str(unit.path)
        done.extend(verify(target, by, at, cwd, git_root))
    return done


def _verify_instruction(instruction: InstructionFile, section: str | None, by: str, stamp: str, cwd: Path,
                        git_root: Path | None) -> list[str]:
    found_path = find_sidecar(instruction.path.parent, git_root)
    sidecar = Sidecar(found_path or (git_root or cwd).resolve() / SIDECAR)
    text = instruction.path.read_text(encoding="utf-8")
    lines = text.split("\n")
    found = references(instruction, Repository(sidecar.base), text)
    available = sections(text)
    chosen = available if section is None else [_match_section(section, available, instruction.path)]
    names = []
    for title, start, end in chosen:
        inside = [r for r in found.references if start <= r.line <= end]
        sources = sorted({_relative(s, sidecar.base) for s in instruction_sources(inside)})
        name = _unit_name(instruction.path, sidecar.base, title)
        sidecar.add(name, by, stamp, sources, section_hash(lines[start - 1 : end]))
        names.append(name)
    sidecar.save()
    return names


def _match_section(wanted: str, available: list[tuple[str | None, int, int]], path: Path):
    if not wanted:
        untitled = [s for s in available if s[0] is None]
        if untitled:
            return untitled[0]
        raise TrustError(f"{path.name} has no text before its first section")
    titled = [s for s in available if s[0]]
    for test in (lambda t: t == wanted, lambda t: t.casefold() == wanted.casefold(),
                 lambda t: _slug(t) == _slug(wanted)):
        matches = [s for s in titled if test(s[0])]
        if matches:
            return matches[0]
    names = ", ".join(f'"{s[0]}"' for s in titled) or "none"
    raise TrustError(f'no section "{wanted}" in {path.name}; sections: {names}')


def _verify_knowledge(path: Path, by: str, stamp: str) -> None:
    """Append to `verified` in the OKF front matter, leaving the rest of the file as it is."""
    doc = load_document(path, path.parent)
    if doc.meta is None or not isinstance(doc.meta.get("type"), str):
        raise TrustError(f"{path.name} is neither an agent instruction file nor an OKF document")
    entries = [dict(e) for e in schema.verifications(doc)] + [{"by": by, "at": stamp}]
    block = ["verified:"] + [f"  - {_flow(entry)}" for entry in entries]
    path.write_text("\n".join(replace_front_matter_key(doc.text.split("\n"), "verified", block)),
                    encoding="utf-8", newline="\n")
    check = load_document(path, path.parent)
    if check.meta is None or len(schema.verifications(check)) != len(entries):
        raise TrustError(f"could not update verified in {path.name}: {check.meta_error}")


def set_generated(lines: list[str], by: str, stamp: str) -> list[str]:
    """OKF `generated` set to who rewrote the document and when (`verified` is left alone)."""
    return replace_front_matter_key(lines, "generated", [f"generated: {_flow({'by': by, 'at': stamp})}"])


def replace_front_matter_key(lines: list[str], key: str, block: list[str]) -> list[str]:
    """Replace a top-level front matter key and its indented lines with `block`, or add it at the end."""
    lines = list(lines)
    end = front_matter_end(lines)  # 1-based line of the closing ---
    start = next((i for i in range(1, end - 1) if re.match(rf"^{re.escape(key)}\s*:", lines[i])), None)
    if start is None:
        lines[end - 1 : end - 1] = block
        return lines
    stop = start + 1
    while stop < end - 1 and (not lines[stop].strip() or lines[stop][0] in " \t-"):
        stop += 1
    lines[start:stop] = block
    return lines


def _flow(entry: dict) -> str:
    parts = []
    for key, value in entry.items():
        text = str(value)
        plain = _PLAIN_ACTOR_RE.match(text) and text[:1] not in ("-", "?", ":", "@")
        parts.append(f"{key}: {text if plain else _quote(text)}")
    return "{ " + ", ".join(parts) + " }"


def _quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


