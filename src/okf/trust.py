def _concepts(root: Path, bundles: list[Path] | None) -> list[tuple[Path, Path]]:
    """OKF documents and their bundle roots: given bundles, or any .md with a `type` in its front matter."""
    if bundles:
        found = []
        for bundle in bundles:
            loaded = Bundle.load(bundle)
            found.extend((doc.path, loaded.root) for doc in loaded.concepts())
        return found
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(filenames):
            path = Path(dirpath) / name
            if (not name.endswith(".md") or name in ("index.md", "log.md", "AGENTS.md", "CLAUDE.md")
                    or instruction_scope(path, root) is not None):
                continue
            try:
                with path.open(encoding="utf-8") as handle:
                    if handle.readline().strip() != "---":
                        continue
            except (OSError, UnicodeDecodeError):
                continue
            doc: Document = load_document(path, root)
            if doc.meta and isinstance(doc.meta.get("type"), str):
                found.append((path, _bundle_root(path.parent, root)))
    return found


def _bundle_root(directory: Path, root: Path) -> Path:
    """The highest directory of an unbroken chain of index.md files above a document."""
    best = directory
    while directory != root and (directory.parent / "index.md").exists() and (directory / "index.md").exists():
        directory = directory.parent
        best = directory
    return best


def _verifications(value) -> list[tuple[datetime, str]]:
    entries = [value] if isinstance(value, dict) else value if isinstance(value, list) else []
    result = []
    for entry in entries:
        if isinstance(entry, dict):
            at, by = parse_instant(entry.get("at")), entry.get("by")
            if at is not None and isinstance(by, str):
                result.append((at, by.strip()))
    return result


def _unit_name(path: Path, base: Path, title: str | None) -> str:
    return _relative(path, base) + (f"#{title}" if title else "")


def _slug(text: str) -> str:
    return re.sub(r"[\s]+", "-", re.sub(r"[^\w\s-]", "", text.strip().lower()))


def _unique(items) -> list:
    result = []
    for item in items:
        if item not in result:
            result.append(item)
    return result


def _relative(path: Path, base: Path) -> str:
    try:
        return Path(os.path.relpath(path, base)).as_posix()
    except ValueError:
        return Path(path).as_posix()


def _show(path: Path, root: Path) -> str:
    shown = _relative(path, root)
    return shown + "/" if Path(path).is_dir() and not shown.endswith("/") else shown


def _day(moment: datetime) -> str:
    return moment.astimezone(timezone.utc).date().isoformat()
